"""Generate sotto_worker/protocol/{card,demo}.py from the shared JSON Schemas.

The zod schemas in packages/shared are the source of truth; `pnpm gen` writes the JSON
Schemas and then runs this script. tests/test_card_protocol.py fails if a committed
model is stale.
"""

import argparse
import subprocess
import sys
from pathlib import Path

WORKER = Path(__file__).resolve().parents[1]
SCHEMAS = WORKER.parents[1] / "packages" / "shared" / "schema"
OUTPUTS = {"card.py": "card.v1.schema.json", "demo.py": "demo.v1.schema.json"}
DEFAULT_OUT_DIR = WORKER / "sotto_worker" / "protocol"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args()
    for output, schema in OUTPUTS.items():
        generate(SCHEMAS / schema, args.out_dir / output)


def generate(schema: Path, output: Path) -> None:
    result = subprocess.run(  # noqa: S603 - fixed argv
        [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(schema),
            "--input-file-type",
            "jsonschema",
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--target-python-version",
            "3.12",
            "--disable-timestamp",
            "--use-annotated",
            "--field-constraints",
            "--use-standard-collections",
            "--use-union-operator",
            "--enum-field-as-literal",
            "all",
            "--use-title-as-name",
            # Keep UUIDs as strings checked by the schema's pattern, exactly like zod's z.uuid().
            "--type-mappings",
            "string+uuid=string",
            # No lax coercion ("3" → 3): reject exactly what zod rejects.
            "--strict-types",
            "str",
            "int",
            "bool",
            "--formatters",
            "builtin",
            "--custom-file-header",
            f"# GENERATED by scripts/gen_card_model.py from {schema.name}. Do not edit.",
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    # Format with fixed settings (--isolated ignores config files) so the output never depends
    # on where the generator runs or on later ruff config changes.
    formatted = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--isolated", "--line-length", "100", "-"],
        input=result.stdout,
        check=True,
        capture_output=True,
        text=True,
    )
    output.write_text(formatted.stdout)


if __name__ == "__main__":
    main()
