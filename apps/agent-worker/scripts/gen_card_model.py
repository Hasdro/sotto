"""Generate sotto_worker/protocol/card.py from the shared card JSON Schema.

The zod schema in packages/shared is the source of truth; `pnpm gen` writes the JSON
Schema and then runs this script. tests/test_card_protocol.py fails if the committed
model is stale.
"""

import argparse
import subprocess
import sys
from pathlib import Path

WORKER = Path(__file__).resolve().parents[1]
SCHEMA = WORKER.parents[1] / "packages" / "shared" / "schema" / "card.v1.schema.json"
DEFAULT_OUTPUT = WORKER / "sotto_worker" / "protocol" / "card.py"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    result = subprocess.run(  # noqa: S603 - fixed argv
        [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input",
            str(SCHEMA),
            "--input-file-type",
            "jsonschema",
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--target-python-version",
            "3.12",
            "--disable-timestamp",
            "--use-annotated",
            "--field-constraints",
            "--use-standard-collections",
            "--use-union-operator",
            "--enum-field-as-literal",
            "all",
            "--use-title-as-name",
            # Keep UUIDs as strings checked by the schema's pattern, exactly like zod's z.uuid().
            "--type-mappings",
            "string+uuid=string",
            # No lax coercion ("3" → 3): reject exactly what zod rejects.
            "--strict-types",
            "str",
            "int",
            "bool",
            "--formatters",
            "builtin",
            "--custom-file-header",
            "# GENERATED by scripts/gen_card_model.py from card.v1.schema.json. Do not edit.",
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    # Format with fixed settings (--isolated ignores config files) so the output never depends
    # on where the generator runs or on later ruff config changes.
    formatted = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--isolated", "--line-length", "100", "-"],
        input=result.stdout,
        check=True,
        capture_output=True,
        text=True,
    )
    args.output.write_text(formatted.stdout)


if __name__ == "__main__":
    main()
