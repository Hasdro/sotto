const tables = { en, ar } as const;
export type Locale = keyof typeof tables;
export const LOCALES: readonly Locale[] = ["en", "ar"];

export type Vars = Record<string, string | number>;

/** Looks up a string and fills `{name}` placeholders. Unknown placeholders stay visible. */
export function t(key: StringKey, locale: Locale = "en", vars?: Vars): string {
  const raw: string = tables[locale][key];
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

export function directionOf(locale: Locale): "ltr" | "rtl" {
  return locale === "ar" ? "rtl" : "ltr";
}

/** Numbers and decimals in the locale's digits (Western digits in both, as UAE apps do). */
export function formatNumber(value: number, locale: Locale, fractionDigits = 0): string {
  return new Intl.NumberFormat(locale === "ar" ? "ar-AE" : "en-US", {
    minimumFractionDigits: fractionDigits,
    maximumFractionDigits: fractionDigits,
  }).format(value);
}
